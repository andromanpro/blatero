"""Local JSONL containers. Compression is storage, not a new conversation."""
from __future__ import annotations

import contextlib
import hashlib
import os
import time
from pathlib import Path

MAX_EXPANDED = 128 * 1024 * 1024
CACHE_LIMIT = 256 * 1024 * 1024
SPAN_CHUNK_BYTES = 256 * 1024
MAX_SPAN_MESSAGE_BYTES = 8 * 1024 * 1024
MAX_COMPRESSED_SPAN_BYTES = 512 * 1024 * 1024


def message_span(path, number, *, seconds=120):
    """Read one primary line and hash its exact prefix with bounded memory.

    Plain live journals can exceed a gigabyte. Skip their large tool lines in
    chunks, without copying or weakening the prefix hash. Compressed input keeps
    an expansion budget. Only the selected message is retained in memory.
    """
    if type(number) is not int or number < 1:
        raise ValueError('Нужен положительный номер строки')
    path = Path(path)
    started = time.monotonic()
    digest, selected = hashlib.sha256(), bytearray()
    index, expanded = 1, 0

    def check_time():
        if time.monotonic() - started > seconds:
            raise ValueError('Превышен лимит времени чтения сообщения')

    check_time()
    with open_jsonl(path) as stream:
        while True:
            check_time()
            raw = stream.readline(SPAN_CHUNK_BYTES)
            if not raw:
                if index == number and selected:
                    return bytes(selected), digest.hexdigest()
                raise ValueError('Строка сообщения не найдена')
            expanded += len(raw)
            if path.suffix == '.zst' and expanded > MAX_COMPRESSED_SPAN_BYTES:
                raise ValueError('Превышен лимит распаковки сообщения')
            digest.update(raw)
            if index == number:
                if len(selected) + len(raw) > MAX_SPAN_MESSAGE_BYTES:
                    raise ValueError('Выбранное сообщение слишком большое')
                selected.extend(raw)
            if raw.endswith(b'\n'):
                if index == number:
                    return bytes(selected), digest.hexdigest()
                index += 1


def is_jsonl(path):
    return str(path).lower().endswith((".jsonl", ".jsonl.zst"))


def canonical(path):
    path = Path(path)
    return path.with_suffix("") if path.name.lower().endswith(".jsonl.zst") else path


def session_files(folder, *, exclude=()):
    """Prefer a live plain journal over its compressed copy, deterministically."""
    found = {}
    for current, dirs, names in os.walk(folder, followlinks=False):
        dirs[:] = sorted(d for d in dirs if d not in exclude and not (Path(current)/d).is_symlink()
                         and not (hasattr(Path(current)/d, "is_junction") and (Path(current)/d).is_junction()))
        for name in sorted(names):
            path = Path(current)/name
            if is_jsonl(path) and not path.is_symlink():
                key = str(canonical(path))
                if key not in found or path.suffix == ".jsonl":
                    found[key] = path
    return list(found.values())


@contextlib.contextmanager
def open_jsonl(path):
    """Lazy import keeps panel Python 3.12 usable; worker needs Python 3.14."""
    path = Path(path)
    if path.suffix != ".zst":
        with path.open("rb") as stream:
            yield stream
        return
    try:
        from compression import zstd
    except ImportError as exc:
        raise ValueError("Чтение JSONL.zst требует Python 3.14") from exc
    try:
        with zstd.open(path, "rb") as stream:
            yield stream
    except (zstd.ZstdError, EOFError) as exc:
        raise ValueError("Повреждён или не завершён архив JSONL.zst") from exc


def materialize(path, cache, *, max_bytes=MAX_EXPANDED, seconds=10):
    """Bounded, disposable worker cache; original archives are never modified."""
    path, cache = Path(path), Path(cache)
    if path.suffix != ".zst":
        return path
    before = path.stat()
    key = hashlib.sha256(f"{path}:{before.st_mtime_ns}:{before.st_size}".encode()).hexdigest()
    cache.mkdir(parents=True, exist_ok=True)
    target = cache/(key + ".expanded")
    if target.is_file():
        return target
    # Only files generated by this helper, inside its dedicated cache directory.
    entries = sorted(cache.glob("*.expanded"), key=lambda p: p.stat().st_mtime_ns)
    total = sum(p.stat().st_size for p in entries)
    for old in entries:
        if total + max_bytes <= CACHE_LIMIT:
            break
        total -= old.stat().st_size
        old.unlink()
    tmp = target.with_suffix(".tmp")
    started, size = time.monotonic(), 0
    try:
        with open_jsonl(path) as source, tmp.open("wb") as dest:
            while True:
                chunk = source.read(min(256 * 1024, max_bytes + 1 - size))
                if not chunk:
                    break
                size += len(chunk)
                if size > max_bytes:
                    raise ValueError(f"JSONL.zst превышает лимит распаковки {max_bytes} байт")
                if time.monotonic() - started > seconds:
                    raise ValueError("JSONL.zst превышает лимит времени распаковки")
                dest.write(chunk)
        after = path.stat()
        if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
            raise ValueError("Архив изменился во время чтения")
        os.replace(tmp, target)
        return target
    finally:
        tmp.unlink(missing_ok=True)
